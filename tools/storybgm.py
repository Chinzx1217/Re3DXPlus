"""storybgm.py <main>: each story select's fixed race music -> src/storybgm.h.

clEffStoryType::getBgm(period, sound source) (0x857d28c): the select's row of the table at
0x973a5c0 (0x158 bytes a select), emBgmType at +0x54 + 4 * (15 * period + source), -1 none;
clSeqStdDayTimeSelectThread::run (0x87781d2) takes period 0's in the story and sets the BGM
line to it (nsMenuCheck::getBgmSelectIdx: its place in the source's list at 0x93dd780, 25 ids
a source). A select's races take its periods that have one, in order (select 7's first race
period 1's: its movie is period 0; select 9's second period 2's).

Output: STORYBGM[select 0..111][race 0..1][source 0..2] the BGM line (0 none), the emBgmType
not on a list (the ending's 54) as -1."""
import os
import struct
import sys

d = open(sys.argv[1], "rb").read()
ph, n = struct.unpack_from("<I", d, 0x1c)[0], struct.unpack_from("<H", d, 0x2c)[0]
segs = [struct.unpack_from("<8I", d, ph + 32 * i) for i in range(n)]


def rd(va, size):
    for t, off, v, _, fs, *_ in segs:
        if t == 1 and v <= va < v + fs:
            return d[off + va - v:off + va - v + size]
    raise KeyError(hex(va))


ids = [list(struct.unpack("<25i", rd(0x93dd780 + 100 * s, 100))) for s in range(3)]
rows = []
for t in range(112):
    base = 0x973a5c0 + 0x158 * t
    periods = [[struct.unpack("<i", rd(base + 0x54 + 4 * (15 * p + s), 4))[0] for s in range(3)] for p in range(5)]
    races = [p for p in periods if any(v != -1 for v in p)][:2]
    while len(races) < 2:
        races.append([-1, -1, -1])
    rows.append([[(ids[s].index(v) if v in ids[s][1:] else -1) if v != -1 else 0 for s, v in enumerate(r)] for r in races])
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "storybgm.h"), "w") as o:
    o.write("/* Generated by tools/storybgm.py from the arcade's clEffStoryType table: do not edit. */\n")
    o.write("#ifndef STORYBGM_H\n#define STORYBGM_H\n\n")
    o.write("/* by story select (get_story_index), its race and the BGM sound source: the BGM line its\n"
            " * race plays (clEffStoryType::getBgm), 0 the player's choice, -1 one not on the list */\n")
    o.write("static const signed char STORYBGM[112][2][3] = {\n")
    for t, r in enumerate(rows):
        o.write("  { { %d, %d, %d }, { %d, %d, %d } }, /* %d */\n" % (*r[0], *r[1], t))
    o.write("};\n\n#endif\n")
print("written")
