"""storycut.py <arcade root>: the story's in-race lines (Cut::clCutIn::DataLoad's
data/cutin/jp/CutIn<n>.txt, CutIn110_Even/_Odd; the 10-in-a-row's own file left to menupack's
CUTIN_FILE) -> src/storycut.h and tools/storycut_texts.txt.

DataLoad reads a file as tokens: its header ECUTIN_B, then records of ten (type, its round,
the distance, the event, nsCutinDisp::eChar, the expression, the face's place, the way, the
text, the end) as long as fscanf gets ten, the text through Utf8ToUnicode, once a record. Row k
of a file is its k-th record (the recompiled DataLoad counts them: rc_utf8_line). Each row
names its text (menupack: STORYCUT_TEXT_BASE + text, font 3, '#' a space, "\\n" or "¥n" a new
line) and its face (STORYCUT_FACE_BASE + face: cell expression - 1 of the character's sheet,
as the 10-in-a-row's), both shared by the rows that have the same."""
import os
import re
import sys

root = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
d = os.path.join(root, "data", "cutin", "jp")


def key(n):
    m = re.match(r"CutIn(\d+)(.*)\.txt$", n)
    return (int(m.group(1)), m.group(2))


def mixed(b):
    """a token as text: UTF-8, its stray Shift-JIS bytes (two of the files' "…") as that"""
    out, i = "", 0
    while i < len(b):
        for k in (1, 2, 3, 4):
            try:
                out += b[i:i + k].decode("utf-8")
                i += k
                break
            except UnicodeDecodeError:
                pass
        else:
            out += b[i:i + 2].decode("cp932", errors="replace")
            i += 2
    return out


names = sorted((n for n in os.listdir(d) if re.match(r"CutIn\d+(_Even|_Odd)?\.txt$", n)), key=key)
texts, faces, rows, files = {}, {}, [], []
for n in names:
    tok = [mixed(t) for t in open(os.path.join(d, n), "rb").read().split()]
    first = len(rows)
    i = 1 if tok and tok[0].startswith("ECUTIN_") else 0
    while i + 10 <= len(tok):
        r = tok[i:i + 10]
        i += 10
        text = r[8].replace("#", " ").replace("¥n", "\\n")
        char = r[4].split("::")[-1]
        try:
            expr = int(r[5])
        except ValueError:
            expr = 1
        t = texts.setdefault(text, len(texts))
        f = faces.setdefault((char, expr), len(faces))
        rows.append((t, f))
    files.append((n, first, len(rows) - first))

with open(os.path.join(here, "storycut_texts.txt"), "w", encoding="utf-8") as o:
    o.write("# generated by tools/storycut.py: T<tab>text id<tab>text, F<tab>face id<tab>eChar<tab>expression\n")
    for t, k in texts.items():
        o.write("T\t%d\t%s\n" % (k, t))
    for (c, e), k in faces.items():
        o.write("F\t%d\t%s\t%d\n" % (k, c, e))

with open(os.path.join(here, "..", "src", "storycut.h"), "w") as o:
    o.write("/* Generated by tools/storycut.py from data/cutin/jp: do not edit. */\n")
    o.write("#ifndef STORYCUT_H\n#define STORYCUT_H\n\n")
    o.write("/* the story's in-race line files and their rows (Cut::clCutIn::DataLoad's records) */\n")
    o.write("#define STORYCUT_FILES %d\n#define STORYCUT_ROWS %d\n" % (len(files), len(rows)))
    o.write("#define STORYCUT_TEXT_BASE 120000 /* + text: its pre-rendered line (menupack.py) */\n")
    o.write("#define STORYCUT_FACE_BASE 124000 /* + face: its face */\n")
    o.write("typedef struct { const char *name; unsigned short first, n; } storycut_file;\n")
    o.write("typedef struct { unsigned short text, face; } storycut_row;\n")
    o.write("static const storycut_file STORYCUT_FILE[STORYCUT_FILES] = {\n")
    for n, a, c in files:
        o.write('  { "%s", %d, %d },\n' % (n, a, c))
    o.write("};\nstatic const storycut_row STORYCUT_ROW[STORYCUT_ROWS] = {\n")
    for k in range(0, len(rows), 8):
        o.write("  " + " ".join("{ %d, %d }," % r for r in rows[k:k + 8]) + "\n")
    o.write("};\n\n#endif\n")
print("%d files, %d rows, %d texts, %d faces" % (len(files), len(rows), len(texts), len(faces)))
